// Options carries everything the renderers need.
type Options struct {
	Account *account.Account
	Masque  *account.MasqueAccount
	Config  config.Config
}

// Clash renders a complete mihomo/clash configuration.
func Clash(nodes []model.Node, opt Options) string {
	var b strings.Builder
	b.WriteString("# generated by warp-sub\n")
	b.WriteString("mixed-port: 7890\n")
	b.WriteString("allow-lan: false\n")
	b.WriteString("mode: rule\n")
	b.WriteString("log-level: info\n")
	b.WriteString("ipv6: true\n\n")
	b.WriteString("proxies:\n")

	names := make([]string, 0, len(nodes))
	for _, n := range nodes {
		name := sanitize(n.Label())
		names = append(names, name)
		b.WriteString("  - " + proxyEntry(name, n, opt) + "\n")
	}
	if len(names) == 0 {
		b.WriteString("  []\n")
	}

	b.WriteString("\nproxy-groups:\n")
	b.WriteString("  - name: \"WARP-自动\"\n")
	b.WriteString("    type: url-test\n")
	b.WriteString(fmt.Sprintf("    url: \"%s\"\n", opt.Config.Subtpl.TestURL))
	b.WriteString("    interval: 300\n")
	b.WriteString("    tolerance: 50\n")
	b.WriteString("    proxies:\n")
	for _, n := range names {
		b.WriteString("      - \"" + n + "\"\n")
	}
	b.WriteString("  - name: \"WARP-手动\"\n")
	b.WriteString("    type: select\n")
	b.WriteString("    proxies:\n")
	b.WriteString("      - \"WARP-自动\"\n")
	for _, n := range names {
		b.WriteString("      - \"" + n + "\"\n")
	}

	// region group: only nodes exiting in an allowed country
	if len(opt.Config.VLESS.AllowedCountries) > 0 {
		allow := map[string]bool{}
		for _, c := range opt.Config.VLESS.AllowedCountries {
			allow[strings.ToUpper(strings.TrimSpace(c))] = true
		}
		matched := make([]string, 0)
		for _, n := range nodes {
			if n.EgressCountry != "" && allow[n.EgressCountry] {
				matched = append(matched, sanitize(n.Label()))
			}
		}
		if len(matched) > 0 {
			b.WriteString("  - name: \"出口合格\"\n")
			b.WriteString("    type: select\n")
			b.WriteString("    proxies:\n")
			for _, m := range matched {
				b.WriteString("      - \"" + m + "\"\n")
			}
		}
	}

	// per-domain groups: only nodes that actually reached that site
	for _, domain := range opt.Config.VLESS.VerifyDomains {
		domain = strings.TrimSpace(domain)
		if domain == "" {
			continue
		}
		host := domain
		if h, _, err := net.SplitHostPort(domain); err == nil {
			host = h
		}
		matched := make([]string, 0)
		for _, n := range nodes {
			if n.DomainOK != nil && n.DomainOK[host] {
				matched = append(matched, sanitize(n.Label()))
			}
		}
		if len(matched) == 0 {
			continue
		}
		b.WriteString("  - name: \"可用 " + host + "\"\n")
		b.WriteString("    type: select\n")
		b.WriteString("    proxies:\n")
		for _, m := range matched {
			b.WriteString("      - \"" + m + "\"\n")
		}
	}

	b.WriteString("\nrules:\n")
	b.WriteString("  - GEOIP,CN,DIRECT\n")
	b.WriteString("  - MATCH,WARP-手动\n")
	return b.String()
}

func proxyEntry(name string, n model.Node, opt Options) string {
	acct := opt.Account
	mtu := opt.Config.Warp.MTU
	if mtu == 0 {
		mtu = 1280
	}
	priv := ""
	pub := ""
	addr := "172.16.0.2/32"
	addrv6 := ""
	reserved := ""
	if acct != nil {
		priv = acct.PrivateKey
		pub = acct.PublicKey
		addr = acct.Address()
		addrv6 = acct.Address6()
		if r := acct.ReservedBytes(opt.Config.Warp.Reserved); len(r) == 3 && (r[0]|r[1]|r[2]) != 0 {
			reserved = fmt.Sprintf("%d,%d,%d", r[0], r[1], r[2])
		}
	}

	switch n.Class {
	case model.ClassWG, model.ClassWGDomain:
		parts := []string{
			`name: "` + name + `"`,
			`type: wireguard`,
			`server: ` + n.Server,
			`port: ` + strconv.Itoa(n.Port),
			`ip: ` + addr,
		}
		if addrv6 != "" {
			parts = append(parts, `ipv6: `+addrv6)
		}
		parts = append(parts,
			`private-key: "`+priv+`"`,
			`public-key: "`+pub+`"`,
			`udp: true`,
			`mtu: `+strconv.Itoa(mtu),
			`remote-dns-resolve: true`,
			`dns: [1.1.1.1, 1.0.0.1]`,
		)
		if reserved != "" {
			parts = append(parts, `reserved: [`+reserved+`]`)
		}
		return "{ " + strings.Join(parts, ", ") + " }"

	case model.ClassMasque:
		mq := opt.Masque
		if mq == nil {
			return `{ name: "` + name + `", type: direct }`
		}
		parts := []string{
			`name: "` + name + `"`,
			`type: masque`,
			`server: ` + n.Server,
			`port: ` + strconv.Itoa(n.Port),
			`private-key: "` + mq.PrivateKey + `"`,
			`public-key: "` + mq.PublicKey + `"`,
			`ip: ` + mq.Address(),
		}
		if v6 := mq.Address6(); v6 != "" {
			parts = append(parts, `ipv6: `+v6)
		}
		parts = append(parts, `mtu: `+strconv.Itoa(mtu), `udp: true`)
		sni := n.SNI
		if sni == "" {
			sni = account.MasqueSNI
		}
		parts = append(parts, `sni: `+sni)
		return "{ " + strings.Join(parts, ", ") + " }"

	case model.ClassVless:
		v := opt.Config.VLESS
		parts := []string{
			`name: "` + name + `"`,
			`type: vless`,
			`server: ` + n.Server,
			`port: ` + strconv.Itoa(n.Port),
			`uuid: ` + v.UUID,
			`network: ws`,
			`tls: true`,
			`udp: true`,
			`servername: ` + v.WorkerHost,
			`client-fingerprint: ` + orDefault(v.Fingerprint, "chrome"),
			`ws-opts: {path: "` + orDefault(v.Path, "/") + `", headers: {Host: ` + v.WorkerHost + `}}`,
		}
		if v.ECH.Enabled && v.ECH.ClashConfig != "" {
			parts = append(parts, `ech-opts: {enable: true, config: "`+v.ECH.ClashConfig+`"}`)
		}
		return "{ " + strings.Join(parts, ", ") + " }"
	}
	return "{ name: \"" + name + "\", type: direct }"
}

// V2Ray renders a base64 encoded subscription of share links.
func V2Ray(nodes []model.Node, opt Options) string {
	var lines []string
	acct := opt.Account
	mtu := opt.Config.Warp.MTU
	if mtu == 0 {
		mtu = 1280
	}
	for _, n := range nodes {
		switch n.Class {
		case model.ClassWG, model.ClassWGDomain:
			if acct == nil {
				continue
			}
			q := url.Values{}
			q.Set("publicKey", acct.PublicKey)
			q.Set("address", acct.Address())
			q.Set("mtu", strconv.Itoa(mtu))
			q.Set("keepAlive", "25")
			q.Set("allowedIPs", "0.0.0.0/0,::/0")
			if r := acct.ReservedBytes(opt.Config.Warp.Reserved); len(r) == 3 && (r[0]|r[1]|r[2]) != 0 {
				q.Set("reserved", fmt.Sprintf("%d,%d,%d", r[0], r[1], r[2]))
			}
			host := n.Server
			lines = append(lines, fmt.Sprintf("wireguard://%s@%s:%d?%s#%s",
				url.QueryEscape(acct.PrivateKey), host, n.Port, q.Encode(), url.QueryEscape(n.Label())))
		case model.ClassVless:
			v := opt.Config.VLESS
			q := url.Values{}
			q.Set("encryption", "none")
			q.Set("security", "tls")
			q.Set("type", "ws")
			q.Set("host", v.WorkerHost)
			q.Set("sni", v.WorkerHost)
			q.Set("fp", orDefault(v.Fingerprint, "chrome"))
			q.Set("path", orDefault(v.Path, "/"))
			if ech := v.ECH.Query(); ech != "" {
				q.Set("ech", ech)
			}
			label := n.Label()
			if marks := domainMarks(n); marks != "" {
				label += " · " + marks
			}
			lines = append(lines, fmt.Sprintf("vless://%s@%s:%d?%s#%s",
				v.UUID, n.Server, n.Port, q.Encode(), url.QueryEscape(label)))
		case model.ClassMasque:
			// v2rayA has no MASQUE outbound; skipped on purpose
		}
	}
	return base64.StdEncoding.EncodeToString([]byte(strings.Join(lines, "\n")))
}

// CountLinks reports how many nodes a target can actually use.
func CountLinks(nodes []model.Node, target string) int {
	n := 0
	for _, node := range nodes {
		if target == "v2ray" && node.Class == model.ClassMasque {
			continue
		}
		n++
	}
	return n
}

// domainMarks renders "agy✓ gpt✗" for a node.
func domainMarks(n model.Node) string {
	if len(n.DomainOK) == 0 {
		return ""
	}
	var parts []string
	for host, ok := range n.DomainOK {
		short := host
		if i := strings.IndexByte(short, '.'); i > 0 {
			short = short[:i]
		}
		if ok {
			parts = append(parts, short+"✓")
		} else {
			parts = append(parts, short+"✗")
		}
	}
	sort.Strings(parts)
	return strings.Join(parts, " ")
}

func sanitize(s string) string {
	s = strings.ReplaceAll(s, `"`, "'")
	s = strings.ReplaceAll(s, "\n", " ")
	return s
}

func orDefault(v, def string) string {
	if strings.TrimSpace(v) == "" {
		return def
	}
	return v
}
